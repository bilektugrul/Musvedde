const dictionaries = { tr, en };

function initialLocale() {
  try {
    const saved = localStorage.getItem('musvedde.locale');
    if (saved && dictionaries[saved]) return saved;
  } catch {}
  return (navigator.language || '').toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export const locale = signal(initialLocale());

export function setLocale(value) {
  const next = dictionaries[value] ? value : 'en';
  locale.value = next;
  document.documentElement.lang = next;
  try { localStorage.setItem('musvedde.locale', next); } catch {}
}

document.documentElement.lang = locale.value;

export function t(key, ...args) {
  const entry = dictionaries[locale.value][key] ?? en[key] ?? key;
  return typeof entry === 'function' ? entry(...args) : entry;
}

export function formatDateTime(ms) {
  const date = new Date(ms);
  const now = new Date();
  const sameDay = date.toDateString() === now.toDateString();
  const options = sameDay
    ? { hour: '2-digit', minute: '2-digit' }
    : date.getFullYear() === now.getFullYear()
      ? { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }
      : { day: 'numeric', month: 'short', year: 'numeric' };
  return date.toLocaleString(locale.value === 'tr' ? 'tr-TR' : 'en-US', options);
}
